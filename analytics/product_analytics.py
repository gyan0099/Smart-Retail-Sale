"""
Smart Retail Sales Analytics & Visualization System
Product Analytics Engine
Evaluates top and bottom selling products, categories, profitability, and Pareto ranking.
"""

import pandas as pd
import numpy as np
from typing import Dict, Any, List

class ProductAnalytics:
    """Computes SKU, category, and profitability rankings."""

    @staticmethod
    def get_top_products(df: pd.DataFrame, n: int = 10, by: str = "Revenue") -> pd.DataFrame:
        """Returns top N products ranked by Revenue or Quantity."""
        if "Product Name" not in df.columns:
            return pd.DataFrame()

        prod_summary = df.groupby(["Product ID", "Product Name", "Category"]).agg(
            Total_Revenue=("Revenue", "sum"),
            Total_Profit=("Profit", "sum"),
            Total_Quantity=("Quantity", "sum"),
            Total_Orders=("Order ID", "nunique"),
            Avg_Unit_Price=("Unit Price", "mean")
        ).reset_index()

        prod_summary["Profit_Margin_%"] = ((prod_summary["Total_Profit"] / prod_summary["Total_Revenue"]) * 100).round(2)
        sort_col = "Total_Revenue" if by == "Revenue" else "Total_Quantity"
        return prod_summary.sort_values(by=sort_col, ascending=False).head(n).reset_index(drop=True)

    @staticmethod
    def get_bottom_products(df: pd.DataFrame, n: int = 10, by: str = "Revenue") -> pd.DataFrame:
        """Returns lowest N performing products."""
        if "Product Name" not in df.columns:
            return pd.DataFrame()

        prod_summary = df.groupby(["Product ID", "Product Name", "Category"]).agg(
            Total_Revenue=("Revenue", "sum"),
            Total_Profit=("Profit", "sum"),
            Total_Quantity=("Quantity", "sum"),
            Total_Orders=("Order ID", "nunique")
        ).reset_index()

        prod_summary["Profit_Margin_%"] = ((prod_summary["Total_Profit"] / prod_summary["Total_Revenue"]) * 100).round(2)
        sort_col = "Total_Revenue" if by == "Revenue" else "Total_Quantity"
        return prod_summary.sort_values(by=sort_col, ascending=True).head(n).reset_index(drop=True)

    @staticmethod
    def get_category_breakdown(df: pd.DataFrame) -> pd.DataFrame:
        """Aggregates revenue, profit, and volume by Category."""
        if "Category" not in df.columns:
            return pd.DataFrame()

        cat_df = df.groupby("Category").agg(
            Revenue=("Revenue", "sum"),
            Profit=("Profit", "sum"),
            Cost=("Cost", "sum"),
            Units_Sold=("Quantity", "sum"),
            Total_Orders=("Order ID", "nunique")
        ).reset_index()

        total_rev = cat_df["Revenue"].sum()
        cat_df["Revenue_Share_%"] = ((cat_df["Revenue"] / total_rev) * 100).round(2) if total_rev > 0 else 0
        cat_df["Profit_Margin_%"] = ((cat_df["Profit"] / cat_df["Revenue"]) * 100).round(2)
        return cat_df.sort_values(by="Revenue", ascending=False).reset_index(drop=True)

    @staticmethod
    def get_subcategory_breakdown(df: pd.DataFrame) -> pd.DataFrame:
        """Aggregates metrics by Category and Sub-Category."""
        if "Sub-Category" not in df.columns:
            return pd.DataFrame()

        sub_df = df.groupby(["Category", "Sub-Category"]).agg(
            Revenue=("Revenue", "sum"),
            Profit=("Profit", "sum"),
            Units_Sold=("Quantity", "sum")
        ).reset_index()

        sub_df["Profit_Margin_%"] = ((sub_df["Profit"] / sub_df["Revenue"]) * 100).round(2)
        return sub_df.sort_values(by="Revenue", ascending=False).reset_index(drop=True)

    @staticmethod
    def get_pareto_analysis(df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes Pareto (80/20) analysis on products:
        Calculates cumulative percentage of total sales generated by top products.
        """
        if "Product Name" not in df.columns or "Revenue" not in df.columns:
            return pd.DataFrame()

        prod_rev = df.groupby("Product Name")["Revenue"].sum().reset_index()
        prod_rev = prod_rev.sort_values(by="Revenue", ascending=False).reset_index(drop=True)
        
        total_rev = prod_rev["Revenue"].sum()
        prod_rev["Cumulative_Revenue"] = prod_rev["Revenue"].cumsum()
        prod_rev["Cumulative_Percentage"] = ((prod_rev["Cumulative_Revenue"] / total_rev) * 100).round(2)
        prod_rev["Rank"] = range(1, len(prod_rev) + 1)
        prod_rev["Rank_Percentage"] = ((prod_rev["Rank"] / len(prod_rev)) * 100).round(2)
        return prod_rev
